# 학생 정보를 담은 딕셔너리 리스트 생성
students = [
    {"이름": "김철수", "나이": 20, "전공": "컴퓨터공학과"},
    {"이름": "이영희", "나이": 22, "전공": "영어영문학과"},
    {"이름": "박민수", "나이": 21, "전공": "경영학과"},
    {"이름": "최수진", "나이": 23, "전공": "수학과"}
]

# 딕셔너리의 '나이' 키를 기준으로 리스트 정렬
# lambda를 사용하여 각 요소(x)에서 '나이' 값을 추출해 비교 기준으로 삼음
students.sort(key=lambda x: x["나이"])

print("나이 순으로 정렬된 학생 목록:")
# 정렬된 리스트를 순회하며 포맷에 맞춰 출력
for s in students:
    print(f"{s['이름']} ({s['나이']}세) - {s['전공']}")